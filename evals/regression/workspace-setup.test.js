// Exercises setup-workspace.ps1 against a temporary meta-repo fixture.
// This locks Helix's AGENTS.md-only instruction surface at the runtime boundary.

const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { spawnSync } = require('node:child_process');

const WORKSPACE_ROOT = path.resolve(__dirname, '..', '..', '..');
const HELIX_ROOT = path.join(WORKSPACE_ROOT, 'helix');
const SETUP_SCRIPT = path.join(HELIX_ROOT, 'scripts', 'setup-workspace.ps1');
const GENERATED_MARKER = '<!-- Generated by helix/scripts/setup-workspace.ps1 -->';

function writeFile(filePath, content) {
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, content, 'utf8');
}

function mkdir(dirPath) {
  fs.mkdirSync(dirPath, { recursive: true });
}

function runPowerShellFile(scriptPath, args, cwd) {
  const candidates = process.platform === 'win32'
    ? ['pwsh.exe', 'powershell.exe']
    : ['pwsh'];

  for (const command of candidates) {
    const result = spawnSync(
      command,
      ['-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', scriptPath, ...args],
      { cwd, encoding: 'utf8' }
    );

    if (result.error && result.error.code === 'ENOENT') {
      continue;
    }

    return { command, ...result };
  }

  throw new Error(`No PowerShell executable found. Tried: ${candidates.join(', ')}`);
}

function seedMetaRepoFixture() {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'helix-workspace-setup-'));

  writeFile(path.join(root, '.helix', 'context-providers.yml'), [
    'providers:',
    '  code_review_graph:',
    '    mode: off',
    '',
  ].join('\n'));

  writeFile(path.join(root, 'helix-repos.yml'), [
    'schema_version: 1',
    'defaults:',
    '  default_branch: main',
    'repos:',
    '  - id: service-a',
    '    remote: https://github.com/example-org/service-a.git',
    '    local_path: workspaces/demo/repos/service-a',
    '    default_branch: main',
    '',
  ].join('\n'));

  writeFile(path.join(root, 'workspaces', 'demo', 'workspace.yml'), [
    'schema_version: 1',
    'id: demo',
    'display_name: Demo',
    'status: draft',
    'mode: interactive',
    'workflow: full-rpi',
    'phase:',
    '  current: setup',
    '  last_completed: null',
    'repos:',
    '  - repo_id: service-a',
    '    role: primary',
    '    branch: main',
    '',
  ].join('\n'));

  writeFile(path.join(root, 'templates', 'mental-model.md.template'), [
    '# Mental Model',
    '',
    '## Domain Glossary',
    '',
    '## Flag Inventory',
    '',
    '## Coupling Map',
    '',
    '## Behavior Conditions',
    '',
    '## State Diagrams',
    '',
    '## Surprise Log',
    '',
  ].join('\n'));

  const repoRoot = path.join(root, 'workspaces', 'demo', 'repos', 'service-a');
  writeFile(path.join(repoRoot, 'AGENTS.md'), [
    '# service-a AGENTS Guide',
    '',
    '- Purpose: test service fixture.',
    '- Verify with the local unit test suite.',
    '',
  ].join('\n'));
  writeFile(path.join(repoRoot, 'src', 'AGENTS.md'), [
    '# src AGENTS Guide',
    '',
    '- Keep source-only conventions here.',
    '',
  ].join('\n'));
  mkdir(path.join(repoRoot, 'tests'));

  writeFile(path.join(root, '.github', 'instructions', 'demo.workspace.instructions.md'), [
    '---',
    'applyTo: "workspaces/demo/repos/**"',
    '---',
    '<!-- AUTO-GENERATED FILE. DO NOT EDIT MANUALLY. -->',
    GENERATED_MARKER,
    '',
    '# Legacy generated summary',
    '',
  ].join('\n'));

  writeFile(path.join(root, '.github', 'instructions', 'user-authored.instructions.md'), [
    '---',
    'applyTo: "**/*.cs"',
    '---',
    '',
    '# User-authored instructions',
    '',
    'This file must remain because Helix did not generate it.',
    '',
  ].join('\n'));

  return root;
}

test('setup-workspace emits AGENTS settings and cleans only Helix-generated instruction summaries', () => {
  const root = seedMetaRepoFixture();
  const result = runPowerShellFile(SETUP_SCRIPT, ['-Workspace', 'demo', '-TargetRoot', root], HELIX_ROOT);

  assert.equal(
    result.status,
    0,
    [
      `setup-workspace.ps1 failed via ${result.command}`,
      `stdout:\n${result.stdout}`,
      `stderr:\n${result.stderr}`,
    ].join('\n\n')
  );

  const workspaceFile = path.join(root, 'demo.code-workspace');
  assert.ok(fs.existsSync(workspaceFile), 'workspace file was not generated');
  const workspace = JSON.parse(fs.readFileSync(workspaceFile, 'utf8'));
  assert.equal(workspace.settings['chat.useAgentsMdFile'], true);
  assert.equal(workspace.settings['chat.useNestedAgentsMdFiles'], true);
  assert.equal(workspace.settings['chat.useCustomizationsInParentRepositories'], true);

  const generatedInstructions = path.join(root, '.github', 'instructions', 'demo.workspace.instructions.md');
  const userInstructions = path.join(root, '.github', 'instructions', 'user-authored.instructions.md');
  assert.equal(fs.existsSync(generatedInstructions), false, 'Helix-generated .instructions.md summary was not removed');
  assert.ok(fs.existsSync(userInstructions), 'user-authored .instructions.md file should be preserved');
  assert.doesNotMatch(fs.readFileSync(userInstructions, 'utf8'), new RegExp(GENERATED_MARKER.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')));

  const repoStatePath = path.join(root, '.helix', 'repo-state', 'service-a.yml');
  const repoCapabilitiesPath = path.join(root, '.helix', 'repo-capabilities', 'service-a.yml');
  assert.ok(fs.existsSync(repoStatePath), 'repo-state was not generated');
  assert.ok(fs.existsSync(repoCapabilitiesPath), 'repo-capabilities was not generated');

  const repoState = fs.readFileSync(repoStatePath, 'utf8');
  assert.match(repoState, /state: ready/);
  assert.match(repoState, /root_agents: true/);
  assert.match(repoState, /nested_agents: true/);
  assert.match(repoState, /tests_present: true/);
  assert.doesNotMatch(repoState, /^\s*instructions:/m, 'repo-state should not contain legacy instruction readiness');

  assert.ok(fs.existsSync(path.join(root, '.helix', 'active-workspace.yml')), 'active workspace file was not generated');
  assert.ok(fs.existsSync(path.join(root, 'workspaces', 'demo', 'mental-model.md')), 'mental model was not seeded');
});
