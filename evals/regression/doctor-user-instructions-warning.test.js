// Verifies that doctor.ps1 warns (without deleting) when user-authored
// instruction surfaces are present alongside Helix's AGENTS.md surface.

const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { spawnSync } = require('node:child_process');

const WORKSPACE_ROOT = path.resolve(__dirname, '..', '..', '..');
const HELIX_ROOT = path.join(WORKSPACE_ROOT, 'helix');
const DOCTOR_SCRIPT = path.join(HELIX_ROOT, 'scripts', 'doctor.ps1');
const HELIX_GENERATED_MARKER = '<!-- Generated by helix/scripts/setup-workspace.ps1 -->';

function writeFile(filePath, content) {
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, content, 'utf8');
}

function runPowerShellFile(scriptPath, args, cwd) {
  const candidates = process.platform === 'win32' ? ['pwsh.exe', 'powershell.exe'] : ['pwsh'];
  for (const command of candidates) {
    const result = spawnSync(
      command,
      ['-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', scriptPath, ...args],
      { cwd, encoding: 'utf8' }
    );
    if (result.error && result.error.code === 'ENOENT') continue;
    return { command, ...result };
  }
  throw new Error(`No PowerShell executable found. Tried: ${candidates.join(', ')}`);
}

function seedMinimalMetaRoot() {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'helix-doctor-userinstr-'));

  writeFile(path.join(root, '.helix', 'context-providers.yml'), [
    'providers:',
    '  code_review_graph:',
    '    mode: off',
    '',
  ].join('\n'));

  writeFile(path.join(root, '.helix', 'install-state.yml'), [
    'schema_version: 1',
    'installed_at: 2026-05-04T00:00:00Z',
    '',
  ].join('\n'));

  writeFile(path.join(root, 'helix-repos.yml'), [
    'schema_version: 1',
    'defaults:',
    '  default_branch: main',
    'repos: []',
    '',
  ].join('\n'));

  return root;
}

test('doctor-user-instructions: warns on .github/copilot-instructions.md and leaves it on disk', () => {
  const root = seedMinimalMetaRoot();
  const filePath = path.join(root, '.github', 'copilot-instructions.md');
  const original = '# User-authored copilot instructions\n\nDo X, then Y.\n';
  writeFile(filePath, original);

  const r = runPowerShellFile(DOCTOR_SCRIPT, ['-TargetRoot', root], root);
  const combined = `${r.stdout || ''}\n${r.stderr || ''}`;

  assert.match(combined, /copilot-instructions\.md/i, `expected warning. Got:\n${combined}`);
  assert.ok(fs.existsSync(filePath), 'doctor must not delete the user-authored file');
  assert.equal(fs.readFileSync(filePath, 'utf8'), original, 'doctor must not modify the user-authored file');
});

test('doctor-user-instructions: warns on user-authored .github/instructions/*.instructions.md', () => {
  const root = seedMinimalMetaRoot();
  const filePath = path.join(root, '.github', 'instructions', 'my-rules.instructions.md');
  const original = '# Custom instructions\n\nProject-specific rules.\n';
  writeFile(filePath, original);

  const r = runPowerShellFile(DOCTOR_SCRIPT, ['-TargetRoot', root], root);
  const combined = `${r.stdout || ''}\n${r.stderr || ''}`;

  assert.match(combined, /my-rules\.instructions\.md/i, `expected warning. Got:\n${combined}`);
  assert.ok(fs.existsSync(filePath), 'doctor must not delete the user-authored file');
});

test('doctor-user-instructions: does NOT warn on Helix-generated .instructions.md summaries', () => {
  const root = seedMinimalMetaRoot();
  const filePath = path.join(root, '.github', 'instructions', 'service-a.instructions.md');
  const helixGenerated = `${HELIX_GENERATED_MARKER}\n# Helix summary for service-a\n`;
  writeFile(filePath, helixGenerated);

  const r = runPowerShellFile(DOCTOR_SCRIPT, ['-TargetRoot', root], root);
  const combined = `${r.stdout || ''}\n${r.stderr || ''}`;

  assert.doesNotMatch(
    combined,
    /service-a\.instructions\.md/i,
    `Helix-generated summary must not trigger the user-authored warning. Got:\n${combined}`
  );
  assert.ok(fs.existsSync(filePath), 'doctor must not delete files of any kind');
});

